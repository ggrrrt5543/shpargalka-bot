def detect_subject(text: str) -> str:
    """Автоопределение предмета по тексту вопроса.

    Возвращает ключ предмета или 'auto' если не удалось определить.
    """
    text_lower = text.lower()
    scores: dict[str, int] = {}

    for subject, keywords in SUBJECT_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in text_lower)
        if score > 0:
            scores[subject] = score

    if not scores:
        return "auto"

    # Возвращаем предмет с максимальным score
    best = max(scores, key=scores.get)
    # Минимум 2 совпадения для уверенности
    if scores[best] >= 2:
        return best
    return "auto"
